"""Build the Kaggle kernel (run.py + kernel-metadata.json) for one video's voiceover.

Usage: python3 kaggle/build_kernel.py runs/<slug>/voice/config.json lexicon.json <out_dir> <kaggle_user>

config.json (written by Claude):
  {"title": str, "lang": "en", "tries": 4,
   "jobs": [{"name": "main", "kind": "main", "script": str, "strict": [...], "hard_cut_before": [...]},
            {"name": "short", "kind": "short", "script": str},
            {"name": "reel", "kind": "short", "script": str}],
   "only": {"main": [5]}}            # optional, redo run: only these beats
A script may be in beat format ([Name | mood]) or in the what-if-script-studio voice format
(=== BEAT 01 | ... ===, [softly] line, [pause 1.0]); the studio format is converted here.
"""
import json, os, re, string, sys, ast

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen  # noqa: E402  (parsing helpers shared with the GPU script)


def tags_to_mood(tags):
    ms = [gen.ALIASES.get(t.lower().strip(), t.lower().strip()) for t in tags]
    if len(ms) > 1 and ("deep" in ms or "serious" in ms):
        return "deep"
    for m in ms:
        if m in gen.PRESETS:
            return m
    return "neutral"


def studio_to_beats(text):
    out = []
    for raw in text.splitlines():
        s = raw.strip()
        if not s or re.match(r"^(TITLE|LANGUAGE|LANG|TOTAL_WORDS|MOOD|SETTINGS|KEY_BEATS|HARD_CUT_BEFORE)\s*:", s, re.I):
            continue
        m = re.match(r"^=+\s*BEAT\b(.*?)=*$", s, re.I)
        if m:
            parts = [p.strip(" =") for p in m.group(1).split("|") if p.strip(" =")]
            out.append(f"\n[{string.capwords((parts[-1] if parts else 'Beat').lower())}]")
            continue
        m = re.match(r"^\[pause\s+([\d.]+)\]$", s, re.I)
        if m:
            out.append(f"(pause {m.group(1)})"); continue
        m = re.match(r"^((?:\[[A-Za-z ]+\]\s*)+)(.*)$", s)
        if m:
            tags = re.findall(r"\[([A-Za-z ]+)\]", m.group(1))
            out.append(f"{{{tags_to_mood(tags)}}} {m.group(2).strip()}"); continue
        out.append(s)
    return "\n".join(out).strip("\n")


def prepare(cfg):
    title = cfg.get("title")
    for j in cfg["jobs"]:
        if re.search(r"^=+\s*BEAT", j["script"], re.M | re.I):
            m = re.search(r"^TITLE\s*:\s*(.+)$", j["script"], re.M | re.I)
            title = title or (m.group(1).strip() if m else None)
            j["script"] = studio_to_beats(j["script"])
            j["hard_cut_before"] = []      # the studio's [pause 1.5] already makes the hard cut
        j["script"] = j["script"].strip("\n")
        j.setdefault("kind", "short" if j["name"].startswith(("short", "reel")) else "main")
        j.setdefault("strict", ["hook"])
        j.setdefault("hard_cut_before", [])
    cfg["title"] = title or "What If"
    cfg.setdefault("lang", "en")
    cfg["tries"] = int(cfg.get("tries", 4))
    return cfg


def self_test(cfg, lex):
    pat = gen.lexicon_pattern(lex)
    ok = True
    for j in cfg["jobs"]:
        beats = gen.parse(j["script"])
        assert beats, f"{j['name']}: no beats parsed"
        words = 0
        print(f"\n{j['name']} ({j['kind']}) — {len(beats)} beats")
        for i, b in enumerate(beats, 1):
            _, ps = gen.pieces(b["text"], b["mood"])
            for c, _, _ in ps:
                assert not (re.search(r"[{}]|\((beat|pause)", c, re.I) or re.search(r"\[[a-z ]+\]", c, re.I)), b["name"]
                if re.search(r"\d", c):
                    print(f"     ⚠ digits left: {c[:80]}"); ok = False
            words += sum(len(c.split()) for c, _, _ in ps)
            flags = (" strict" if gen.is_strict(j, b["name"]) else "") + (" hard-cut" if gen.is_hard(j, b["name"]) else "")
            lw = sorted({w for c, _, _ in ps for w in gen.lexicon_words(c, lex, pat)})
            print(f"  {i:02d} {b['name'][:34]:<34} {', '.join(sorted({m for _, m, _ in ps})):<24}{flags}"
                  + (f"  lexicon: {', '.join(lw)}" if lw else ""))
        print(f"  ~{words} words ≈ {words / 150:.1f} min spoken")
    return ok


RUN_TEMPLATE = r'''# Auto-generated by kaggle/build_kernel.py — KR's What If Explained voiceover
import glob, json, os, shutil, subprocess, sys

JOB = json.loads(__JOB__)
GEN = __GEN__
AUDIO_EXT = (".m4a", ".mp3", ".wav", ".ogg", ".aac", ".flac", ".opus", ".webm", ".mp4")
NAMES = sorted(list(JOB["_moods"]) + ["default"], key=len, reverse=True)

def sh(cmd):
    print("$", cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True)

gpu = subprocess.run(["nvidia-smi", "-L"], capture_output=True, text=True)
if gpu.returncode != 0:
    sys.exit("❌ no GPU: the kernel must run with a GPU accelerator")
print("✅", gpu.stdout.strip(), flush=True)
if shutil.which("ffmpeg") is None:
    sh("apt-get -qq update && apt-get -qq install -y ffmpeg")

ENV = "/tmp/cbenv"
sh("pip -q install uv")
sh(f"uv venv {ENV} --python 3.11 --seed -q --allow-existing")
sh(f'uv pip install -q --python {ENV}/bin/python chatterbox-tts==0.1.7 "setuptools<81" openai-whisper pyloudnorm soundfile')

# voice samples from the private dataset (file name = mood: soft, wonder, deep, warm, playful, default)
refs = {}
os.makedirs("/tmp/refs", exist_ok=True)
for src in sorted(glob.glob("/kaggle/input/**/*", recursive=True)):
    if not src.lower().endswith(AUDIO_EXT):
        continue
    n = os.path.basename(src).lower()
    mood = next((s for s in NAMES if s in n), "default")
    mood = JOB["_aliases"].get(mood, mood)
    dst = f"/tmp/refs/{mood}.wav"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-ac", "1", "-ar", "24000",
                    "-af", "silenceremove=start_periods=1:start_threshold=-45dB", "-t", "15", dst], check=True)
    refs[mood] = dst
print("🎙️ voice samples:", ", ".join(sorted(refs)) or "none (default voice)", flush=True)

open("/tmp/gen.py", "w").write(GEN)
job = {k: v for k, v in JOB.items() if not k.startswith("_")}
job.update(refs=refs, parts="/kaggle/working/parts", final="/kaggle/working/final",
           report="/kaggle/working/report.json")
json.dump(job, open("/tmp/job.json", "w"))
p = subprocess.Popen([f"{ENV}/bin/python", "-u", "/tmp/gen.py", "/tmp/job.json"],
                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
for line in p.stdout:
    print(line, end="", flush=True)
if p.wait() != 0:
    sys.exit("❌ generation failed")
'''


def main():
    cfg_path, lex_path, out_dir, user = sys.argv[1:5]
    cfg = prepare(json.load(open(cfg_path)))
    lex = {w.lower(): v for w, v in json.load(open(lex_path)).items() if not w.startswith("_") and v}
    cfg["lexicon"] = lex
    ok = self_test(cfg, lex)
    cfg["_moods"] = sorted(set(gen.PRESETS) | set(gen.ALIASES))
    cfg["_aliases"] = gen.ALIASES
    os.makedirs(out_dir, exist_ok=True)
    gen_src = open(os.path.join(HERE, "gen.py")).read()
    run = RUN_TEMPLATE.replace("__JOB__", repr(json.dumps(cfg))).replace("__GEN__", repr(gen_src))
    ast.parse(run)
    open(os.path.join(out_dir, "run.py"), "w").write(run)
    meta = {"id": f"{user}/kr-voiceover", "title": "kr-voiceover", "code_file": "run.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_internet": True,
            "dataset_sources": [f"{user}/kr-voice-samples"],
            "competition_sources": [], "kernel_sources": [], "model_sources": []}
    json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
    print(f"\nkernel written to {out_dir} · {cfg['title']} · lang {cfg['lang']} · tries {cfg['tries']}")
    print("SELF-TEST OK" if ok else "SELF-TEST: fix the ⚠ lines (spell digits out) and rebuild")
    sys.exit(0 if ok else 2)


if __name__ == "__main__":
    main()
